-- ---------------------------------------------------------------------------
-- 1. TABLES
-- ---------------------------------------------------------------------------

-- profiles: 1:1 mirror of auth.users, holds the public username
create table if not exists public.profiles (
  id         uuid primary key references auth.users (id) on delete cascade,
  username   text not null unique check (char_length(username) between 3 and 20),
  created_at timestamptz not null default now()
);

-- gossipbar: the posts ("gossips")
-- images holds up to 2 filenames (reference the "gossip" storage bucket)
create table if not exists public.gossipbar (
  id         bigint generated by default as identity primary key,
  user_id    uuid references auth.users (id) on delete set null,
  username   text not null,                       -- denormalised so feeds need no join
  title      text not null check (char_length(title) <= 300),
  content    text not null,                       -- HTML from the rich text editor
  images     text[2],                             -- [filename_1, filename_2] or nulls
  likes      bigint not null default 0,
  created_at timestamptz not null default now()
);

-- likes: one row per (user, post) — enables toggling + "isliked" flag
create table if not exists public.likes (
  user_id    uuid not null references auth.users (id) on delete cascade,
  post_id    bigint not null references public.gossipbar (id) on delete cascade,
  created_at timestamptz not null default now(),
  primary key (user_id, post_id)
);

-- messages: the Campus Connect live chat feed (streamed via Supabase Realtime)
create table if not exists public.messages (
  id         bigint generated by default as identity primary key,
  user_id    uuid references auth.users (id) on delete cascade,
  username   text not null,
  message    text not null,
  created_at timestamptz not null default now()
);

-- ---------------------------------------------------------------------------
-- 2. INDEXES
-- ---------------------------------------------------------------------------
create index if not exists gossipbar_created_idx on public.gossipbar (created_at desc);
create index if not exists likes_post_idx        on public.likes (post_id);
create index if not exists messages_created_idx  on public.messages (created_at desc);

-- ---------------------------------------------------------------------------
-- 3. ROW LEVEL SECURITY
--    The UI never touches tables directly — it calls the RPC functions below
--    (SECURITY DEFINER), so base tables can be locked down.
-- ---------------------------------------------------------------------------
alter table public.profiles  enable row level security;
alter table public.gossipbar enable row level security;
alter table public.likes     enable row level security;
alter table public.messages  enable row level security;

-- gossipbar is readable by everyone (feed + shared-post links).
create policy "gossipbar_select" on public.gossipbar for select using (true);

-- profiles / likes / messages have no direct-table policies on purpose:
-- every write happens inside the SECURITY DEFINER functions below.

-- ---------------------------------------------------------------------------
-- 4. STORED FUNCTIONS (RPC) — the backend API
--    security definer + search_path = public
--    => callers can only do exactly what these functions allow.
-- ---------------------------------------------------------------------------

-- Auth: is the username already taken? (returns TRUE = taken)
create or replace function public.checkusername(p_username text)
returns boolean
language sql
security definer
set search_path = public
as $$
  select exists (
    select 1 from public.profiles
    where lower(username) = lower(p_username)
  );
$$;

-- Auth: create / refresh the profile for a freshly signed-up user
create or replace function public.insertusername(p_id uuid, p_username text)
returns boolean
language sql
security definer
set search_path = public
as $$
  insert into public.profiles (id, username)
  values (p_id, p_username)
  on conflict (id) do update set username = excluded.username
  returning true;
$$;

-- Auth: fetch a user's username after login (cached in localStorage by the SPA)
create or replace function public.get_username(p_user_id uuid)
returns text
language sql
security definer
set search_path = public
as $$
  select username from public.profiles where id = p_user_id;
$$;

-- Posts: create a gossip (images arrives as jsonb {0|1: filename|null} from JS)
create or replace function public.insert_into_gossipbar(
  p_uuid    uuid,
  p_title   text,
  p_content text,
  p_images  jsonb
)
returns bigint
language sql
security definer
set search_path = public
as $$
  insert into public.gossipbar (user_id, username, title, content, images, likes)
  select p_uuid, author.username, p_title, p_content,
         array[p_images->>0, p_images->>1]::text[], 0
  from public.profiles author
  where author.id = p_uuid
  returning id;
$$;

-- Posts: paginated feed (limit/offset) with the viewer's "isliked" flag
create or replace function public.fetch_posts(
  user_uuid    uuid,
  limit_count  integer,
  offset_count integer
)
returns table (
  id bigint, username text, title text, content text, images text[],
  likes int, isliked boolean, created_at timestamptz
)
language sql
security definer
set search_path = public
as $$
  select gb.id, gb.username, gb.title, gb.content, gb.images::text[], gb.likes::int,
         exists (select 1 from public.likes l
                 where l.post_id = gb.id and l.user_id = user_uuid) as isliked,
         gb.created_at
  from public.gossipbar gb
  order by gb.created_at desc
  limit limit_count offset offset_count;
$$;

-- Posts: one post by id (renders shared links, e.g. /post.html?id=…)
create or replace function public.fetch_shared_posts(
  user_uuid uuid,
  post_id   bigint
)
returns table (
  id bigint, username text, title text, content text, images text[],
  likes int, isliked boolean, created_at timestamptz
)
language sql
security definer
set search_path = public
as $$
  select gb.id, gb.username, gb.title, gb.content, gb.images::text[], gb.likes::int,
         exists (select 1 from public.likes l
                 where l.post_id = gb.id and l.user_id = user_uuid) as isliked,
         gb.created_at
  from public.gossipbar gb
  where gb.id = post_id;
$$;

-- Posts: only MY posts (profile → "View Posted Gossip")
create or replace function public.fetch_my_posts(
  user_uuid    uuid,
  limit_count  integer,
  offset_count integer
)
returns table (
  id bigint, username text, title text, content text, images text[],
  likes int, isliked boolean, created_at timestamptz
)
language sql
security definer
set search_path = public
as $$
  select gb.id, gb.username, gb.title, gb.content, gb.images::text[], gb.likes::int,
