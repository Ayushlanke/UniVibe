-- Posts: toggle a like (returns TRUE if now liked, FALSE if unliked)
create or replace function public.toggle_like(p_userid uuid, p_postid bigint)
returns boolean
language plpgsql
security definer
set search_path = public
as $$
declare
  is_liked boolean;
begin
  if exists (select 1 from public.likes
             where user_id = p_userid and post_id = p_postid) then
    delete from public.likes where user_id = p_userid and post_id = p_postid;
    update public.gossipbar set likes = greatest(likes - 1, 0) where id = p_postid;
    return false;
  else
    insert into public.likes (user_id, post_id) values (p_userid, p_postid);
    update public.gossipbar set likes = likes + 1 where id = p_postid;
    return true;
  end if;
end;
$$;

-- Posts: delete ONLY your own post (ownership checked server-side)
create or replace function public.delete_gossipbar_post(p_userid uuid, p_postid bigint)
returns boolean
language plpgsql
security definer
set search_path = public
as $$
begin
  delete from public.gossipbar
  where id = p_postid and user_id = p_userid;
  return found;
end;
$$;

-- Chat: send a message (username pulled from profiles server-side)
create or replace function public.insert_message(user_id uuid, message_text text)
returns void
language sql
security definer
set search_path = public
as $$
  insert into public.messages (user_id, username, message)
  select user_id, author.username, message_text
  from public.profiles author
  where author.id = user_id;
$$;

-- Chat: last 30 messages to hydrate the room on load
create or replace function public.fetch_live()
returns table (id bigint, username text, message text, created_at timestamptz)
language sql
security definer
set search_path = public
as $$
  select id, username, message, created_at
  from public.messages
  order by created_at desc
  limit 30;
$$;

-- ---------------------------------------------------------------------------
-- 5. STORAGE — "gossip" bucket for post images (public, up to 2 per post)
-- ---------------------------------------------------------------------------
insert into storage.buckets (id, name, public)
values ('gossip', 'gossip', true)
on conflict (id) do nothing;

create policy "gossip_read" on storage.objects
  for select using (bucket_id = 'gossip');

create policy "gossip_insert" on storage.objects
  for insert to authenticated with check (bucket_id = 'gossip');

-- ---------------------------------------------------------------------------
-- 6. REALTIME — stream new messages to the Campus Connect chat
-- ---------------------------------------------------------------------------
alter publication supabase_realtime add table public.messages;